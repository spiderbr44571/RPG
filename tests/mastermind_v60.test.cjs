'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../app/src/main');
const html=fs.readFileSync(path.join(root,'assets/demo-offline.html'),'utf8');
const style=fs.readFileSync(path.join(root,'assets/mastermind60_identity.css'),'utf8');
const manifest=fs.readFileSync(path.join(root,'AndroidManifest.xml'),'utf8');
const gradle=fs.readFileSync(path.resolve(__dirname,'../app/build.gradle'),'utf8');
const native=fs.readFileSync(path.join(root,'res/drawable-nodpi/mastermind_logo.png'));
const branded=fs.readFileSync(path.join(root,'assets/mastermind_logo.png'));
assert.ok(native.equals(branded),'Launcher logo and WebView brand must use the exact same image');
assert.equal(native.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
const width=native.readUInt32BE(16),height=native.readUInt32BE(20);
assert.ok(width>=96&&height>=96&&width===height,'Minimum square image resolution');
assert.match(manifest,/android:icon="@drawable\/mastermind_logo"/);
assert.match(manifest,/android:roundIcon="@drawable\/mastermind_logo"/);
assert.match(gradle,/versionCode (?:60|61|62|63|64|65|66|68|69)/);
assert.match(html,/>v0\.(?:60|61|62|63|64|65|66|68|69)<\/small>/);
assert.match(html,/const svgHome=`<svg class="r09-home-svg"/);
assert.match(html,/aria-label="Abrir menu principal do Mastermind"/);
assert.doesNotMatch(html,/const svgDie=`<svg class="r09-poly"/);
assert.match(html,/r09-dice"[^>]*>\$\{svgHome\}/);
assert.match(html,/Abrir esta central não realiza rolagens/);
assert.match(html,/href="mastermind60_identity\.css"/);
assert.match(style,/background:transparent!important;background-image:none!important/);
assert.match(style,/#v10-roll-burst \.v101-die svg path:first-child/);
assert.match(style,/var\(--v10-accent,var\(--accent\)\)/);
assert.match(style,/var\(--mm60-icon\)/);
assert.match(style,/v101-die-face/);
assert.match(style,/data-paranormal="base"/);
console.log('PASS v0.60: uploaded brand PNG in Android launcher/WebView, home menu, free-standing dice and theme CSS');
