'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const quality=require('../app/src/main/assets/rpg24_ai_quality.js');
const assets=path.join(__dirname,'../app/src/main/assets');
const ui=fs.readFileSync(path.join(assets,'demo-offline.html'),'utf8');
const native=fs.readFileSync(path.join(__dirname,'../app/src/main/java/dev/rpgmesa/demo/MainActivity.java'),'utf8');
const free=[{id:'sample/compact-chat-7b:free'},{id:'sample/chat-8b:free'},{id:'sample/chat-14b:free'}];
const first=quality.fallbackModels('sample/compact-chat-7b:free',free);
assert.deepEqual(first,['sample/compact-chat-7b:free','sample/chat-8b:free','sample/chat-14b:free']);
assert.deepEqual(quality.fallbackModels('openrouter/free',free),['openrouter/free','sample/compact-chat-7b:free','sample/chat-8b:free']);
assert.deepEqual(quality.fallbackModels('sample/paid',free),['sample/compact-chat-7b:free','sample/chat-8b:free','sample/chat-14b:free']);
assert.deepEqual(quality.fallbackModels('openrouter/free',[]),['openrouter/free']);
assert.deepEqual(quality.fallbackModels('sample/foo:free',[{id:'sample/foo:free'},{id:'sample/bar:free'}]),
 ['sample/foo:free','sample/bar:free','openrouter/free']);
assert.ok(quality.validAnswer('A resposta sobre regras depende da edição.'));
assert.ok(!quality.validAnswer('null'));
assert.ok(!quality.validAnswer('User Safety: safe'));
assert.match(native,/setConnectTimeout\(5500\)/,'native connect timeout reduced');
assert.match(native,/setReadTimeout\(body==null\?16000:19000\)/,'native response budget');
assert.match(native,/if\(\+\+attempt>3\)break/,'bounded 3 cloud attempts');
assert.match(native,/reportProgress\(params\.optString\("_requestId",""\)/,'native progress callback');
assert.ok(native.includes("rpg25-cloud-progress"),'progress event');
assert.ok(native.includes("candidates.add(\"openrouter/free\")"),'automatic free option as last resort');
assert.ok(native.includes('Limite de requisições gratuitas atingido; tente novamente mais tarde'),'no offline fallback in rate-limit');
assert.ok(!native.includes('Limite de requisições gratuitas atingido; use a busca offline'));
assert.match(ui,/action==='chat'\?95000:35000/,'webview wait exceeds native multi-model budget');
assert.match(ui,/AbortSignal\.timeout\(23000\)/,'browser fallback request budget');
assert.ok(ui.includes('rpg25-cloud-progress'),'browser observes live progress');
assert.ok(ui.includes("quality.fallbackModels(data.model,cachedModels,3)"),'web fallback multi model');
assert.ok(ui.includes('class="r11-light-btn r25-retry"'),'explicit re-ask action');
assert.ok(ui.includes("pending.querySelector('.r25-retry')?.addEventListener('click'"),'retry button really works');
const catchText=ui.slice(ui.indexOf("}catch(err){\n   pending.innerHTML='<b>IA gratuita não respondeu"),ui.indexOf("}catch(err){\n  addBubble('<b>Erro na consulta"));
assert.ok(!catchText.includes('localAnswer(query,hits)'), 'NEVER insert offline answer automatically after AI error');
assert.ok(!catchText.includes("mode='offline'"),'never secretly switch to offline mode');
console.log('PASS AI resilience: distinct free fallbacks, 95s > 3 native retries, progress, real retry control, no forced offline search.');
