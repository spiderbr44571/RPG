const assert=require('node:assert/strict');
const E=require('../app/src/main/assets/rpg16_gurps_engine.js');
const s=E.create('Investigador');
assert.equal(s.systemId,'gurps');assert.equal(s.edition,'4e');
let d=E.derived(s);let p=E.spent(s);
assert.equal(d.HP,10);assert.equal(d.FP,10);assert.equal(d.will,10);assert.equal(d.per,10);
assert.equal(d.speed,5);assert.equal(d.move,5);assert.equal(d.dodge,8);
assert.equal(d.basicLift,10);assert.equal(d.thrust,'1d-2');assert.equal(d.swing,'1d');
assert.equal(p.total,0);assert.equal(p.remaining,150);
s.attrs.ST=12;d=E.derived(s);assert.equal(d.HP,12);assert.equal(d.basicLift,14.4);assert.equal(d.thrust,'1d-1');assert.equal(d.swing,'1d+2');
assert.equal(E.spent(s).attribute,20);
s.mod.hp=2;s.mod.will=1;s.mod.speed=.25;
assert.equal(E.spent(s).secondary,14); // HP 4, Will 5, Speed 5
d=E.derived(s);assert.equal(d.HP,14);assert.equal(d.will,11);assert.equal(d.speed,5.25);
assert.equal(E.skillLevel({attr:'DX',diff:'E',points:1},{DX:10}),10);
assert.equal(E.skillLevel({attr:'DX',diff:'A',points:1},{DX:10}),9);
assert.equal(E.skillLevel({attr:'IQ',diff:'H',points:1},{IQ:10}),8);
assert.equal(E.skillLevel({attr:'IQ',diff:'VH',points:1},{IQ:10}),7);
assert.equal(E.skillLevel({attr:'IQ',diff:'VH',points:8},{IQ:10}),10);
assert.equal(E.skillLevel({attr:'DX',diff:'A',points:12},{DX:10}),13);
let roll=E.roll(10,0,()=>1);assert.equal(roll.total,3);assert.equal(roll.grade,'Sucesso decisivo');
roll=E.roll(16,0,()=>2);assert.equal(roll.grade,'Sucesso decisivo');
roll=E.roll(20,0,()=>6);assert.equal(roll.grade,'Falha crítica');
roll=E.roll(13,0,()=>5);assert.equal(roll.total,15);assert.equal(roll.grade,'Falha');
const damage=E.rollDamage('thr+1',s,()=>4);
assert.equal(damage.total,4);assert.equal(damage.faces.length,1);
assert.equal(E.rollDamage('3d+2',s,()=>4).total,14);
const l=E.create('Carga');l.items.push({weight:25,qty:1,equipped:false,dr:0});
const loaded=E.derived(l);assert.equal(loaded.enc,2);assert.equal(loaded.dodge,6);assert.equal(loaded.moveLoaded,3);
l.items.push({weight:0,qty:1,dr:3,equipped:true});assert.equal(E.derived(l).DR,3);
l.advantages.push({name:'Vantagem',points:15});l.disadvantages.push({name:'Desvantagem',points:-10});
assert.equal(E.spent(l).advantages,15);assert.equal(E.spent(l).disadvantages,-10);
console.log('PASS: GURPS 4e – pontos, atributos, secundarias, 3d6, niveis de pericias, dano e carga.');
