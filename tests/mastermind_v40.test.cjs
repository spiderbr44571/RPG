'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../app/src/main/assets'),read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('demo-offline.html'),js=read('mastermind40_canvas_images.js'),css=read('mastermind40_canvas_images.css');
assert.doesNotThrow(()=>new Function(js));
assert.match(html,/<script src="mastermind40_canvas_images\.js"><\/script>/);
assert.match(html,/<link rel="stylesheet" href="mastermind40_canvas_images\.css">/);
assert.ok(html.indexOf('mastermind39_ui.js')<html.indexOf('mastermind40_canvas_images.js'));
assert.match(js,/const MIME=new Set\(\['image\/jpeg','image\/png','image\/webp'\]\)/);
assert.match(js,/MAX_IMAGE=10\*1024\*1024/);
assert.match(js,/toDataURL\('image\/webp',quality\)/);
assert.match(js,/localStorage\.setItem\(KEY,snapshot\(\)\)/);
assert.match(js,/data:image/);
assert.match(js,/node\.width=/);
assert.match(js,/setPointerCapture/);
assert.match(js,/new FileReader/);
assert.match(js,/addFiles\(\[\.\.\.event\.dataTransfer\.files\]\)/);
assert.match(js,/if\(!persist\(\)\)\{app\.S\.nodes\.pop\(\);break\}/);
assert.match(js,/app\.renderCanvas=function\(\)/);
assert.match(html,/S\.nodes\.filter\(n=>n\.type!=='IMAGEM'\)/);
assert.match(html,/'OUTRO','IMAGEM'/);
assert.match(css,/var\(--accent\)/);
for(const file of ['mastermind39_ui.css','mastermind39_ui.js','rpg31_master_table.js'])assert.ok(fs.existsSync(path.join(root,file)));
console.log('PASS Mastermind v0.40: upload, compressao, persistencia, resize, drop e compatibilidade');
