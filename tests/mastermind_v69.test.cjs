'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../app/src/main/assets');
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const src=read('mastermind69_atmosphere.js'),ctx={window:{},console};
assert.doesNotThrow(()=>new Function(src),'atmosphere syntax');
vm.createContext(ctx);vm.runInContext(src,ctx,{filename:'mastermind69_atmosphere.js'});
const A=ctx.window.Mastermind69Atmosphere;
assert.ok(A&&A.THEMES.night.ambient>.65);
assert.equal(A.settings({}).enabled,false,'Old maps must have lighting disabled');
assert.equal(A.settings({atmosphere:{mode:'night',enabled:true}}).ambient,.72);
assert.equal(A.settings({atmosphere:{mode:'night',ambient:3,fogDensity:-4}}).ambient,1);
const scene={width:9,height:9,layers:{walls:[]}};
assert.equal(A.lineOfSight(scene,2.5,2.5,6.5,2.5),true);
scene.layers.walls.push({x:4,y:2,side:'e',kind:'wall'});
assert.equal(A.walls(scene).length,1);
assert.equal(A.lineOfSight(scene,2.5,2.5,6.5,2.5),false,'Opaque wall blocks line-of-sight');
scene.layers.walls[0].kind='door';scene.layers.walls[0].open=false;
assert.equal(A.lineOfSight(scene,2.5,2.5,6.5,2.5),false,'Closed door blocks light');
scene.layers.walls[0].open=true;
assert.equal(A.lineOfSight(scene,2.5,2.5,6.5,2.5),true,'Open door allows light');
const torch=A.ensureLight(scene,3,4,{radius:6,color:'#ffc982'});
assert.equal(scene.lights.length,1);assert.equal(torch.type,'torch');
const shape=A.visibilityPolygon(scene,{x:3.5,y:4.5,radius:6},32);
assert.ok(shape.length>=30&&shape.every(p=>Number.isFinite(p[0])&&Number.isFinite(p[1])),'Raycasting geometry valid');
scene.atmosphere={mode:'paranormal',enabled:true,fogOfWar:true,fogDensity:.5,quality:'economy'};
assert.equal(A.settings(scene).fogOfWar,true);
for(const name of ['rpg29_scene_editor.js','rpg31_master_table.js','rpg31_player_table.js'])assert.doesNotThrow(()=>new Function(read(name)),name);
const editor=read('rpg29_scene_editor.js'),master=read('rpg31_master_table.js'),player=read('rpg31_player_table.js');
for(const needle of ['r69-light-panel','r69-mode','r69-fog-density','r69-enabled','r69-fow','r69-vision','r69-light-color','r69-light-radius','r69-quality','r69-add-light','r69-toggle','r69-delete','atmosphereEngine?.attach'])assert.ok(editor.includes(needle),'Missing editor UI '+needle);
assert.match(master,/Mastermind69Atmosphere\?\.attach\(board,map/);
assert.match(player,/Mastermind69Atmosphere\?\.attach\(board,s,\{cell,player:true\}/);
for(const file of ['demo-offline.html','lan_master.html','lan_scene.html'])assert.ok(read(file).includes('atmosphere.js'),'Missing atmosphere in '+file);
const java=fs.readFileSync(path.resolve(__dirname,'../app/src/main/java/dev/rpgmesa/demo/LocalCampaignServer.java'),'utf8');
for(const name of ['opaqueBoundaries','canSeeThrough','player.optJSONObject("mapExploration")','scene.put("visibleCells"','fogOfWarActive&&!currentVision.contains','scene.put("layers",visiblePaint)','visible.put("image","")'])assert.ok(java.includes(name),'Fog-of-war server protection '+name);
assert.match(java,/path.equals\("\/atmosphere.js"\)/);
assert.match(java,/lights.length\(\)>20/);
assert.match(read('demo-offline.html'),/>v0\.(?:69|70|72|73)<\/small>/);
assert.match(fs.readFileSync(path.resolve(__dirname,'../app/build.gradle'),'utf8'),/versionCode (?:69|70|72|73)/);
console.log('PASS v0.69: 2.5D lighting, fog quality modes, dynamic wall/door shadows, server-side fog of war and safe older maps');
