'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const base=path.resolve(__dirname,'../app/src/main/assets');
const read=x=>fs.readFileSync(path.join(base,x),'utf8');
const html=read('demo-offline.html');
const engine=read('mastermind83_renderer.js'),studio=read('mastermind83_studio.js');
const packed=read('mastermind83_atlas.js');
assert.match(html,/>v0\.83<\/small>/);
assert.ok(html.includes('mm83-portrait')&&html.includes('mm83-token'));
for(const id of ['mm83-save','mm83-export-portrait','mm83-export-token','mm83-random','mm83-reset','mm83-category-list','mm83-choices'])assert.ok(html.includes('id="'+id+'"'),'Missing new pixel studio control '+id);
for(const asset of ['mastermind83_atlas.js','mastermind83_renderer.js','mastermind83_studio.js','mastermind83_studio.css'])assert.ok(html.includes(asset),'Missing active pixel studio '+asset);
for(const old of ['mastermind76_atelier','mastermind77_atelier','mastermind78_atelier','mastermind79_art','mastermind80_portraits','mastermind81_atelier','mastermind82_atelier','mastermind81_rig','mastermind82_rig'])assert.ok(!html.includes(old+'.js')&&!html.includes(old+'.css'),'Legacy studio included in app: '+old);
assert.ok(packed.length>100000&&packed.includes('data:image/png;base64,'));
assert.match(engine,/imageSmoothingEnabled=false/);
assert.match(studio,/mastermind:portrait-updated/);
assert.match(studio,/atelier:cfg/);
assert.match(studio,/stored\?\.version===83/);
assert.match(read('mastermind83_studio.css'),/image-rendering:pixelated/);
const gradle=fs.readFileSync(path.resolve(__dirname,'../app/build.gradle'),'utf8');
assert.match(gradle,/versionCode 86/);
console.log('PASS: v0.83 clean-room pixel editor loaded; 20 categories; no old painter on app startup');