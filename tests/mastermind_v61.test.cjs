'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const a=path.resolve(__dirname,'../app/src/main/assets');
const read=name=>fs.readFileSync(path.join(a,name),'utf8');
const ctx={window:{}};
vm.runInNewContext(read('rpg16_gurps_traits.js'),ctx);
const traits=ctx.window.GURPS4_BASIC_TRAITS;
assert.ok(traits.length>=664,'Catalog must include all indexed traits from the Basic Set source');
const counts=Object.fromEntries(['advantages','disadvantages','perks','quirks'].map(k=>[k,traits.filter(x=>x.category===k).length]));
assert.ok(counts.advantages>=298&&counts.disadvantages>=307&&counts.perks>=17&&counts.quirks>=42);
assert.ok(traits.every(x=>x.name&&x.reference.match(/B\d+/)&&!('description' in x)&&!('local_notes' in x)));
assert.ok(traits.some(x=>x.name==='Combat Reflexes'&&x.points===15));
assert.ok(traits.some(x=>x.points===null),'Variable costs must be manual, not falsely fixed');
const ui=read('rpg16_gurps_ui.js'),html=read('demo-offline.html');
assert.ok(html.indexOf('rpg16_gurps_traits.js')<html.indexOf('rpg16_gurps_ui.js'));
assert.match(ui,/data-edit-skill/);
assert.match(ui,/Object\.assign\(s\.skills\[editingSkillIndex\],values\)/);
assert.match(ui,/editingSkillIndex=-1/);
assert.match(ui,/traitLevelsChanged/);
assert.match(ui,/g-trait-filter-/);
assert.doesNotThrow(()=>new Function(ui),'GURPS UI JS syntax');
assert.doesNotThrow(()=>new Function(read('rpg16_gurps_traits.js')));
assert.match(fs.readFileSync(path.resolve(__dirname,'../app/build.gradle'),'utf8'),/versionCode (?:61|62|63|64|65)/);
assert.match(html,/>v0\.(?:61|62|63|64|65)<\/small>/);
console.log('PASS v0.61: 664 basic traits and non-destructive GURPS skill edits; syntax and Android integration');
