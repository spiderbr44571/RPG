'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {createHost}=require('../campaign-server.cjs');
const assets=path.resolve(__dirname,'../../app/src/main/assets');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'mastermind-lan-test-'));
test('Linux LAN host: real campaign, visual canvas, live tabletop, secrets and persistent scenes',async t=>{
 const host=createHost({assetsDir:assets,dataDir:root,port:0,host:'127.0.0.1'});
 await host.start();
 t.after(()=>host.close());
 const base='http://127.0.0.1:'+host.port;
 const gm={'Authorization':'Bearer '+host.key,'Content-Type':'application/json'};
 const req=async(p,method='GET',body,headers={})=>{
  const r=await fetch(base+p,{method,headers:{...gm,...headers},body:body===undefined?undefined:JSON.stringify(body)});
  const text=await r.text();
  let j;try{j=JSON.parse(text);}catch{j=text;}
  return {status:r.status,headers:r.headers,data:j};
 };
 let x=await fetch(base+'/master');assert.equal(x.status,200);
 const markup=await x.text();
 assert.match(markup,/data-act="maps"/,'Desktop console needs immediate map editor');
 assert.match(markup,/RPG29_EDITOR\.open/);
 const bad=await fetch(base+'/api/admin/campaigns');
 assert.equal(bad.status,403,'Anonymous user may not list campaigns');
 let listing=await req('/api/admin/campaigns');
 assert.deepEqual(listing.data.campaigns,[]);
 let created=await req('/api/admin/campaigns','POST',{name:'Noite no Observatório'});
 assert.equal(created.status,201);assert.ok(created.data.id);
 const cid=created.data.id;
 let detail=await req('/api/admin/campaigns/'+cid);
 assert.equal(detail.status,200);
 assert.equal(detail.data.campaign.name,'Noite no Observatório');
 assert.equal(detail.data.campaign.scenarios.length,1);
 assert.equal(detail.data.campaign.characters.length,0);
 const sceneId=detail.data.campaign.activeScenarioId;
 const one=detail.data.campaign.scenarios[0];
 assert.equal(one.id,sceneId);
 let scenes=await req('/api/admin/campaigns/'+cid+'/scenarios');
 assert.equal(scenes.data.scenarios.length,1);
 one.tokens.push({id:'token-1',name:'Aventureiro',kind:'character',x:4,y:5,systemId:'ordem-paranormal'});
 const saveScene=await req('/api/admin/campaigns/'+cid+'/scenarios','POST',{scenarios:[one],assets:[],activeScenarioId:sceneId});
 assert.equal(saveScene.status,200);
 scenes=await req('/api/admin/campaigns/'+cid+'/scenarios');
 assert.equal(scenes.data.scenarios[0].tokens[0].x,4);
 const map=await req('/api/admin/campaigns/'+cid+'/table');
 assert.equal(map.status,200);
 assert.equal(map.data.scenarios.length,1);
 assert.equal(map.data.movementLimits['token-1'],9);
 assert.equal(map.data.sessionMode,'combat');
 assert.ok(map.data.initiative);
 const pri=await req('/api/admin/campaigns/'+cid+'/canvas','POST',{nodes:[{id:'node-one',title:'Pista secreta',x:10,y:15}]});
 assert.equal(pri.status,200);
 const json=await req('/api/admin/campaigns/'+cid);
 assert.equal(json.data.campaign.canvas[0].title,'Pista secreta');
 const init=await req('/api/admin/campaigns/'+cid+'/initiative','POST',{action:'set',tokenId:'token-1',score:14});
 assert.equal(init.status,200);
 assert.equal(init.data.entries.length,1);
 const shift=await req('/api/admin/campaigns/'+cid+'/advance','POST',{kind:'turn'});
 assert.equal(shift.status,200);
 const inter=await req('/api/admin/campaigns/'+cid+'/session-mode','POST',{mode:'interlude'});
 assert.equal(inter.data.movementUnlimited,true);
 const frozen=await req('/api/admin/campaigns/'+cid+'/advance','POST',{kind:'turn'});
 assert.equal(frozen.status,400);
 const roll=await req('/api/admin/campaigns/'+cid+'/table-roll','POST',{formula:'3d20+5',label:'Percepção'});
 assert.equal(roll.status,200);
 assert.equal(roll.data.faces.length,3);
 assert.equal(roll.data.total,Math.max(...roll.data.faces)+5);
 const denied=await req('/api/admin/campaigns/'+cid+'/canvas','POST',{nodes:[]},{origin:'https://attacker.invalid'});
 assert.equal(denied.status,403);
 const file=path.join(root,'campaigns-linux.json');
 assert.ok(fs.existsSync(file));
 const state=JSON.parse(fs.readFileSync(file));
 assert.equal(state.campaigns[0].canvas[0].title,'Pista secreta');
 assert.ok(state.secret&&state.secret===host.key);
 assert.ok(!markup.includes(host.key),'Admin secret must NOT be in HTML');
 const direct=await fetch(base+'/scene/'+cid);
 assert.equal(direct.status,403,'Unauthenticated player cannot open scene');
 const gameCss=await fetch(base+'/scene-editor.css');
 assert.equal(gameCss.status,200);
 assert.match(gameCss.headers.get('content-type'),/css/);
 const invalid=await req('/api/admin/campaigns/'+cid+'/scenarios','POST',{scenarios:[{id:'bad-scene',name:'Falha',width:9,height:9,tokens:[{id:'a',x:999,y:5}],rooms:[]}],assets:[],activeScenarioId:'bad-scene'});
 assert.equal(invalid.status,400);
});
test('Desktop GM input validates resource limits and session dice',()=>{
 const {rollDice,validateSheet}=require('../campaign-server.cjs');
 const result=rollDice('2d6+2',{mode:'sum'});
 assert.equal(result.faces.length,2);
 assert.equal(result.total,result.faces.reduce((a,b)=>a+b,0)+2);
 assert.throws(()=>rollDice('200d20'),/Use dados/);
 assert.equal(validateSheet({name:'Personagem',resources:{PV:20}}).resources.PV.max,20);
 assert.throws(()=>validateSheet({name:'',resources:{}}));
});
