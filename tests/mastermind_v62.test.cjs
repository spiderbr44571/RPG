'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../app/src/main/assets'),read=n=>fs.readFileSync(path.join(root,n),'utf8');
const engine=read('mastermind62_descriptions.js'),g=read('rpg16_gurps_ui.js'),d=read('rpg18_dnd_ui.js'),order=read('mastermind56_local_powers.js'),html=read('demo-offline.html');
for(const [name,s] of [['descriptions',engine],['gurps',g],['dnd',d],['powers',order],['catalog',read('rpg16_gurps_traits.js')]])assert.doesNotThrow(()=>new Function(s),name+' should parse');
const env={window:{}};vm.runInNewContext(read('rpg16_gurps_traits.js'),env);
const traits=env.window.GURPS4_BASIC_TRAITS;
assert.ok(traits.length>=664);
assert.ok(traits.filter(x=>x.namePt&&x.pagePt).length>=400,'Portuguese user glossary must provide more than 400 actual correspondences');
assert.equal(traits.find(x=>x.name==='Combat Reflexes')?.namePt,'Reflexos em Combate');
assert.equal(traits.find(x=>x.name==='Absolute Direction')?.namePt,'Senso de Direção');
vm.runInNewContext(engine,env);
const api=env.window.Mastermind62Descriptions;
assert.equal(api.find('Reflexos em Combate','gurps')?.name,'Reflexos em Combate');
assert.equal(api.find('Combat Reflexes','gurps')?.name,'Reflexos em Combate');
assert.ok(api.allEntries().some(x=>x.systemId==='gurps'));
assert.match(g,/data-g62-catalog/);
assert.match(g,/x\.namePt/);
assert.match(d,/data-d62-skill/);
assert.match(d,/data-d62-item/);
assert.match(order,/v62-power-description/);
assert.match(html,/mastermind62_descriptions\.js/);
assert.match(html,/mm62-descriptions-trigger/);
assert.match(html,/>v0\.(?:62|63|64|65|66|68|69)<\/small>/);
assert.match(html,/r09-home-door"[^>]*stroke="none"/);
assert.match(read('mastermind60_identity.css'),/\.r09-home-body,html body #r09-dice \.r09-home-door \{stroke:none!important\}/);
assert.match(fs.readFileSync(path.resolve(__dirname,'../app/build.gradle'),'utf8'),/versionCode (?:62|63|64|65|66|68|69)/);
console.log('PASS Mastermind v0.62: translations, icon stroke, universal description lookup and all systems entrypoints');
