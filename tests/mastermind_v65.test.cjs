'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const dir=path.resolve(__dirname,'../app/src/main');
const html=fs.readFileSync(path.join(dir,'assets/demo-offline.html'),'utf8');
const css=fs.readFileSync(path.join(dir,'assets/mastermind38_shell.css'),'utf8');
const logo=fs.readFileSync(path.join(dir,'assets/mastermind_logo.png'));
const nativeLogo=fs.readFileSync(path.join(dir,'res/drawable-nodpi/mastermind_logo.png'));
const gradle=fs.readFileSync(path.resolve(__dirname,'../app/build.gradle'),'utf8');
const splash=html.match(/<div id="mm-loading"[\s\S]*?<\/div><\/div>/)?.[0];
assert.ok(splash,'Real splash must exist in Android WebView HTML');
assert.match(splash,/class="mm-boot-content"/,'Splash content has a structured centered stack');
assert.match(splash,/<img class="mm-boot-logo" src="mastermind_logo\.png"/,'Splash must use the official brand asset');
assert.match(splash,/<strong class="mm-boot-title">Mastermind<\/strong>/,'A dedicated title keeps text alignment deterministic');
assert.match(splash,/<small class="mm-boot-subtitle">Preparando seu espaço\.\.\.<\/small>/);
assert.doesNotMatch(splash,/mm-boot-mark|>M<\/div>/,'Old letter M must be removed');
assert.ok(nativeLogo.equals(logo),'Splash must use exact same image as Android launcher');
assert.equal(logo.subarray(0,8).toString('hex'),'89504e470d0a1a0a','Splash logo is a real PNG');
assert.match(css,/#mm-loading \.mm-boot-content\{[\s\S]*?display:flex;flex-direction:column;align-items:center;justify-content:center/);
assert.match(css,/#mm-loading \.mm-boot-logo\{[\s\S]*?object-fit:contain;object-position:center;margin:0 auto/);
assert.match(css,/#mm-loading \.mm-boot-title\{[\s\S]*?text-align:center/);
assert.match(css,/#mm-loading \.mm-boot-subtitle\{[\s\S]*?text-align:center/);
assert.match(css,/#mm-loading\{[\s\S]*?min-height:100dvh/);
assert.match(css,/:root\.mm-ready #mm-loading\{display:none\}/,'Splash must disappear once loaded');
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.match(gradle,/versionCode (?:65|66|68|69|70|71|72|73)/);
assert.match(html,/>v0\.(?:65|66|68|69|70|71|72|73)<\/small>/);
console.log('PASS Mastermind v0.65: splash logo, centered title/subtitle, small screens, theme, launcher parity');
