'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../app/src/main/assets');
const src=fs.readFileSync(path.join(root,'rpg37_rules.js'),'utf8');
const sandbox={window:{},globalThis:{}};vm.runInNewContext(src,sandbox);
const {skillBudget,ritualBudget}=sandbox.window.RPG37_RULES;
assert.equal(typeof ritualBudget,'function');
const pack={classes:{Combatente:{periciasLivres:'1 + Intelecto',periciasObrigatorias:['Luta ou Pontaria','Fortitude ou Reflexos']},Ocultista:{periciasLivres:'3 + Intelecto',periciasObrigatorias:['Ocultismo','Vontade']}},
 origens:[{nome:'Academico',pericias:['Ciencias','Investigacao']}]};
const skills={class:'Combatente',origin:'Academico',nex:5,attrs:{Intelecto:2},skills:{Luta:1,Fortitude:1,Percepcao:1}};
let budget=skillBudget(skills,pack);
assert.equal(budget.selections.total,3);assert.equal(budget.selections.used,1);
assert.equal(budget.selections.remaining,2);
assert.equal(budget.upgrades.total,0);assert.equal(budget.upgrades.used,0);
assert.equal(budget.upgrades.gradeCap,1);
budget=skillBudget({...skills,skills:{...skills.skills,Percepcao:2}},pack);
assert.equal(budget.selections.used,1,'upgrade must not consume another selection');
assert.equal(budget.upgrades.used,1);
assert.equal(budget.upgrades.excess,1);
assert.ok(budget.invalidGrades.includes('Percepcao'));
budget=skillBudget({...skills,nex:35,skills:{...skills.skills,Percepcao:2}},pack);
assert.equal(budget.upgrades.total,4);assert.equal(budget.upgrades.used,1);assert.equal(budget.upgrades.remaining,3);
assert.equal(budget.invalidGrades.length,0);
budget=skillBudget({...skills,nex:35,skills:{...skills.skills,Percepcao:3}},pack);
assert.ok(budget.invalidGrades.includes('Percepcao'),'expert locked before 70%');
budget=skillBudget({...skills,nex:70,skills:{...skills.skills,Percepcao:3}},pack);
assert.equal(budget.upgrades.total,8);assert.equal(budget.upgrades.used,2);assert.equal(budget.upgrades.remaining,6);
assert.equal(budget.invalidGrades.length,0);
budget=skillBudget({...skills,nex:35,skills:{Luta:2,Fortitude:2,Percepcao:2,Investigacao:2,Ciencias:2}},pack);
assert.equal(budget.upgrades.excess,1,'origin skills upgrades count');
const rituals=[{id:'r1',circulo:1},{id:'r2',circulo:2},{id:'r3',circulo:3},{id:'r4',circulo:4}];
const char={class:'Ocultista',nex:5,rituaisConhecidos:[]};
let r=ritualBudget(char,rituals);assert.equal(r.total,4);assert.equal(r.remaining,4);assert.equal(r.maxCircle,1);
assert.equal(ritualBudget({...char,rituaisConhecidos:['r2']},rituals).illegal.length,1);
r=ritualBudget({...char,nex:25},rituals);assert.equal(r.total,11);assert.equal(r.maxCircle,2);
r=ritualBudget({...char,nex:55},rituals);assert.equal(r.total,20);assert.equal(r.maxCircle,3);
r=ritualBudget({...char,nex:85},rituals);assert.equal(r.total,29);assert.equal(r.maxCircle,4);
r=ritualBudget({...char,nex:99},rituals);assert.equal(r.total,32);
r=ritualBudget({...char,class:'Combatente'},rituals);assert.equal(r.total,0);
const html=fs.readFileSync(path.join(root,'demo-offline.html'),'utf8');
const inline=[...html.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)].filter(a=>!a[1].includes('src=')&&!a[1].includes('application/json'));
for(let i=0;i<inline.length;i++)assert.doesNotThrow(()=>new Function(inline[i][2]),'inline script '+i);
assert.match(html,/fresh=\{\.\.\.sys\.state,name:'Novo agente',photo:''/);
assert.match(html,/update\(id,patch\)\{/);
assert.match(html,/const targetCharacterId=window\.MastermindCharacters\?\.selectedId\?\.\(\)/);
assert.match(html,/updateChar\(\{photo:cvs\.toDataURL\('image\/jpeg',\.78\)\},targetCharacterId\)/);
assert.match(html,/r09-remove-photo/);
assert.match(html,/profile\.dataset\.currentId/);
assert.match(html,/Perícias adicionais/);
assert.match(html,/Upgrades disponíveis/);
assert.match(html,/budget\.upgrades\.excess>0/);
assert.match(html,/budget\.invalidGrades\.includes\(name\)/);
assert.match(html,/refreshRitualPicker/);
assert.match(html,/Number\(s\.circulo\)>b\.maxCircle\?'disabled'/);
assert.match(html,/if\(Number\(r\.circulo\)>b\.maxCircle\)/);
assert.match(html,/if\(b\.remaining<=0\)/);
assert.match(html,/rpg:character-selected/);
assert.match(html,/mastermind44_sheet_rules\.css/);
