'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../app/src/main/assets'),read=f=>fs.readFileSync(path.join(root,f),'utf8');
const html=read('demo-offline.html'),js=read('mastermind39_ui.js'),css=read('mastermind39_ui.css');
const legacy=read('mastermind38_shell.css');
new Function(js);
const allInline=[...html.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)].filter(s=>!s[1].includes('src=')&&!s[1].includes('application/json'));
for(let i=0;i<allInline.length;i++)assert.doesNotThrow(()=>new Function(allInline[i][2]),'inline script '+i);
assert.match(html,/<script src="mastermind39_ui\.js"><\/script>/);
assert.ok(!html.includes('<script src="mastermind38_shell.js"></script>'),'Old shell no longer runs');
assert.match(html,/<link rel="stylesheet" href="mastermind39_ui\.css">/);
assert.match(js,/const controller=\(\)=>window\.MastermindCharacters/);
assert.match(js,/const api=controller\(\)/);
assert.match(js,/if\(!api\|\|!api\.open\(id\)\)/);
assert.match(js,/data-mm39-character/);
assert.match(js,/characterList\(list,char\)/);
assert.match(js,/class="mm39-character-item/);
assert.match(js,/class="mm39-sheet-preview/);
assert.match(js,/c\.name\|\|record\.name/);
assert.match(js,/c\.class/);
assert.match(js,/c\.trail/);
assert.match(js,/NEX /);
assert.match(js,/resources/);
assert.match(js,/photo/);
assert.match(js,/mm39-PV/);
assert.match(js,/header\.appendChild\(button\)/);
assert.match(js,/host\.appendChild\(banner\)/);
assert.match(js,/settingsScreen/);
assert.match(js,/rpg:character-selected/);
assert.match(js,/finally\{document\.documentElement\.classList\.add\('mm-ready'\)\}/);
assert.match(legacy,/:root:not\(\.mm-ready\) \.app/);
const start=html.indexOf('window.MastermindCharacters='),stop=html.indexOf('activateCharacter(selectedChar)',start);
assert.ok(start>0&&stop>start,'real character model exposes its controller before activation');
const controllerHtml=html.slice(start,stop);
assert.match(controllerHtml,/selectedId\(\)\{return selectedChar\}/);
assert.match(controllerHtml,/open\(id\)/);
assert.match(controllerHtml,/demo\.navigate\('sheet'\)/);
assert.match(html,/characters\.push\(\{id,name:fresh\.name,character:fresh\}\);save\(charsKey,characters\);activateCharacter\(id\)/);
assert.match(html,/document\.dispatchEvent\(new CustomEvent\('rpg:character-selected'/);
assert.match(css,/mm39-overview/);
assert.match(css,/mm39-tool-grid/);
assert.match(css,/mm39-character-list/);
assert.match(css,/mm39-more-drawer/);
assert.match(css,/min-height:168px/);
assert.match(css,/background:var\(--accent\)/);
assert.ok(!css.includes('localStorage.clear'));
for(const pref of ['accent-wheel','accent-brightness','heading-font','font-range','motion-toggle','data-v10-theme'])assert.ok(html.includes(pref),'preference unavailable: '+pref);
for(const module of ['rpg11_campaigns.js','rpg28_context_search.js','rpg37_rules.js','rpg18_bestiary.js','rpg33_camera.js'])assert.ok(html.includes(module),'missing module: '+module);
console.log('PASS v0.39: fully redesigned Mastermind shell, direct actual character selection, offline modules and preserved themes');
